"""Structural provider ports; implementations accept and return JSON dictionaries."""
from __future__ import annotations

from collections.abc import Awaitable, Callable
from typing import Any, Protocol

JsonObject = dict[str, Any]
ProgressSink = Callable[[JsonObject], Awaitable[None] | None]


class CancellationToken(Protocol):
    def is_set(self) -> bool: ...


class SpeechToTextProvider(Protocol):
    async def capabilities(self) -> JsonObject: ...
    async def transcribe(self, source: Any, language: str, checkpoint_dir: Any, progress: ProgressSink | None = None) -> JsonObject: ...
    async def release(self) -> None: ...
    async def close(self) -> None: ...
    async def cancel(self) -> None: ...


class CoachModelProvider(Protocol):
    async def capabilities(self) -> JsonObject: ...
    async def complete(self, task: str, system: str, payload: JsonObject, schema: JsonObject) -> JsonObject: ...
    async def release(self) -> None: ...
    async def close(self) -> None: ...


class TextToSpeechProvider(Protocol):
    async def capabilities(self) -> JsonObject: ...
    async def list_voices(self) -> list[JsonObject]: ...
    async def synthesize(self, request: JsonObject, cancel: CancellationToken | None = None) -> JsonObject: ...


class TopicProvider(Protocol):
    async def next(self, request: JsonObject) -> JsonObject: ...


class SessionRepository(Protocol):
    def create_session(self, payload: JsonObject) -> JsonObject: ...
    def get_session(self, session_id: str) -> JsonObject: ...
    def list_sessions(self) -> list[JsonObject]: ...
    def update_session(self, session_id: str, changes: JsonObject, expected_revision: int | None = None) -> JsonObject: ...
    def delete_session(self, session_id: str) -> None: ...
